% Задание 1
% Параметры сигнала для варианта 24
f = 10; % частота сигнала, Гц
A = 5;  % амплитуда
phase = pi / 7; % начальная фаза

% Создание вектора времени с малым шагом для эмуляции непрерывности
t = 0:0.001:0.5; 

y = A * sin(2 * pi * f * t + phase);

figure;
plot(t, y, 'b', 'LineWidth', 1.5);
grid on;
title('Непрерывный сигнал y(t)');
xlabel('Время t, (с');
ylabel('Амплитуда');