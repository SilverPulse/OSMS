% Задание 5: Преобразование Фурье
N = length(y_discrete); % количество отсчетов
Y = fft(y_discrete); % прямое преобразование Фурье

% Вычисляем амплитудный спектр и нормируем его
Y_mag = abs(Y) / N;

% Формируем ось частот от 0 до Fs
f_axis = (0:N-1) * (Fs / N);

figure;
stem(f_axis, Y_mag, 'm', 'LineWidth', 1.5);
grid on;
title('Амплитудный спектр оцифрованного сигнала');
xlabel('Частота f, (Гц)');
ylabel('Амплитуда');