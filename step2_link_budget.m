% =========================================================================
% ФАЙЛ 2: Расчет бюджета восходящего и нисходящего каналов (MAPL)
% =========================================================================

% --- Исходные данные из методички ---
TxPower_BS = 46;      % Мощность передатчика BS, дБм
TxPower_UE = 24;      % Мощность передатчика UE, дБм
AntGain_BS = 21;      % Коэффициент усиления антенны BS, дБи
PenetrationM = 15;    % Запас на проникновение сквозь стены, дБ
IM = 1;               % Запас на интерференцию, дБ
MIMO_Gain = 3;        % Выигрыш от MIMO 2x2, дБ

% Потери в антенно-фидерном тракте (фидер + МШУ + джампер)
FeederLoss = 2.0 + 0.4 + 0.5; % 2.9 дБ

% Чувствительность приемников (рассчитанная в step1)
RxSens_BS = -97.60;   % Чувствительность BS (для UL), дБм
RxSens_UE = -92.99;   % Чувствительность UE (для DL), дБм

% 1. Расчет максимально допустимых потерь в восходящем канале (UL)
MAPL_UL = TxPower_UE - FeederLoss + AntGain_BS + MIMO_Gain - IM - PenetrationM - RxSens_BS

% 2. Расчет максимально допустимых потерь в нисходящем канале (DL)
MAPL_DL = TxPower_BS - FeederLoss + AntGain_BS + MIMO_Gain - IM - PenetrationM - RxSens_UE

% Вывод результатов
fprintf('=========================================\n');
fprintf('MAPL восходящего канала (UL): %.2f дБ\n', MAPL_UL);
fprintf('MAPL нисходящего канала (DL): %.2f дБ\n', MAPL_DL);
fprintf('=========================================\n');