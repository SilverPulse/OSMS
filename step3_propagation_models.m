% =========================================================================
% ФАЙЛ 3: Модели распространения сигналов и графики
% =========================================================================

% Исходные данные
f_GHz = 1.8;         % Частота в ГГц (для UMiNLOS)
f_MHz = 1800;        % Частота в МГц (для COST 231 и Walfish-Ikegami)
hBS = 30;            % Высота антенны БС, м
hms = 1.5;           % Высота антенны телефона, м
MAPL_UL = 126.70;    % Наш лимитирующий порог

% Создаем массив расстояний d (от 10 м до 5000 м с шагом 10 м)
d_m = 10:10:5000;    
d_km = d_m / 1000;   % Перевод в км

% -------------------------------------------------------------------------
% 1. Модель UMiNLOS (микросоты, indoor)
% -------------------------------------------------------------------------
PL_UMiNLOS = 26 * log10(f_GHz) + 22.7 + 36.7 * log10(d_m);

% -------------------------------------------------------------------------
% 2. Модель COST 231 Hata (макросоты)
% -------------------------------------------------------------------------
A = 46.3; 
B = 33.9;
a_hms = 3.2 * (log10(11.75 * hms))^2 - 4.97;
Lclutter = 3;

s = zeros(size(d_km));
idx_large = (d_km >= 1); 
idx_small = (d_km < 1);  

s(idx_large) = 44.9 - 6.55 * log10(f_MHz);
s(idx_small) = (47.88 + 13.9*log10(f_MHz) - 13.9*log10(hBS)) * (1 / log10(50));

PL_COST231 = A + B * log10(f_MHz) - 13.82 * log10(hBS) - a_hms + s .* log10(d_km) + Lclutter;

% -------------------------------------------------------------------------
% 3. Модель Walfisch-Ikegami (макросоты, плотная застройка)
% -------------------------------------------------------------------------
% Типовые значения для города (так как не заданы в условиях):
h_roof = 15;   % Средняя высота зданий, м
w = 15;        % Средняя ширина улиц, м
b = 30;        % Расстояние между центрами зданий, м
phi = 90;      % Сигнал перпендикулярен улице

% Формула 2.10: Потери в свободном пространстве
L0 = 32.44 + 20*log10(f_MHz) + 20*log10(d_km);

% Формула 2.11: Потери за счет переотражений от крыш (L2)
dh_ms = h_roof - hms;
L_ori = 4.0 - 0.114 * phi; % Условие для 55 <= phi < 90
L2 = -16.9 - 10*log10(w) + 10*log10(f_MHz) + 20*log10(dh_ms) + L_ori;

% Формулы 2.12 - 2.16: Потери за счет переотражений от стен (L1)
% Условие: hBS (30м) > h_roof (15м)
dh_BS = hBS - h_roof;
L1_1 = -18 * log10(1 + dh_BS);          % Формула 2.13
ka = 54;                                % Формула 2.14
kd = 18;                                % Формула 2.15
kf = -4 + 0.7 * (f_MHz/925 - 1);        % Формула 2.16
L1 = L1_1 + ka + kd*log10(d_km) + kf*log10(f_MHz) - 9*log10(b);

% Формула 2.9: Итоговые потери NLOS
% Отрицательные значения L1+L2 не учитываются (если <=0, то берем 0)
L_Walfisch = L0 + max(0, L1 + L2); 

% -------------------------------------------------------------------------
% Построение графиков
% -------------------------------------------------------------------------
figure('Name', 'Модели распространения радиосигнала');
hold on; grid on;

plot(d_m, PL_UMiNLOS, 'r-', 'LineWidth', 2);
plot(d_m, PL_COST231, 'b-', 'LineWidth', 2);
plot(d_m, L_Walfisch, 'g-', 'LineWidth', 2);
yline(MAPL_UL, 'k--', 'MAPL UL (126.7 дБ)', 'LineWidth', 1.5);

xlabel('Расстояние между приемником и передатчиком, м');
ylabel('Потери сигнала, дБ');
legend('UMiNLOS', 'COST 231 Hata', 'Walfisch-Ikegami', 'Максимально допустимые потери (UL)', 'Location', 'southeast');
title('Сравнение моделей UMiNLOS, COST 231 и Walfisch-Ikegami');